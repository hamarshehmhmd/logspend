"""Render a plan's drop/sample actions as pipeline config for OTel Collector, Vector and Fluent Bit."""
from __future__ import annotations

from typing import List

TARGETS = ("otel", "vector", "fluentbit")
DEFAULT_FIELD = {"otel": "body", "vector": ".message", "fluentbit": "log"}


def _active(plan: dict) -> List[dict]:
    return [p for p in plan.get("patterns", []) if p.get("action") in ("drop", "sample")]


def _money(p: dict) -> str:
    c = p.get("monthly_cost")
    return f"~${c:,.2f}/mo" if isinstance(c, (int, float)) else ""


def _comment(p: dict) -> str:
    t = p["template"].replace("\n", " ")
    if len(t) > 90:
        t = t[:87] + "..."
    what = "drop" if p["action"] == "drop" else f"sample keep 1 in {p.get('sample_keep') or 10}"
    return f"{p['id']} {what} {_money(p)}: {t}"


def ottl_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_otel(plan: dict, field: str = "body") -> str:
    act = _active(plan)
    drops = [p for p in act if p["action"] == "drop"]
    samples = [p for p in act if p["action"] == "sample"]
    out = [
        "# Generated by logspend: OpenTelemetry Collector filter processor (OTTL).",
        "# Add `filter/logspend` to the processors of your logs pipeline, e.g.",
        "#   service: { pipelines: { logs: { processors: [filter/logspend, batch] } } }",
        "# Run `logspend simulate` on fresh logs before deploying.",
        "processors:",
        "  filter/logspend:",
        "    error_mode: ignore",
        "    logs:",
        "      log_record:",
    ]
    if not drops:
        out.append("        - 'false'  # no drop rules in this plan")
    for p in drops:
        out.append(f"        # {_comment(p)}")
        stmt = f"IsMatch({field}, {ottl_string(p['regex'])})"
        out.append("        - '" + stmt.replace("'", "''") + "'")
    for p in samples:
        out.append(f"# NOT APPLIED {_comment(p)}")
        out.append("#   The filter processor cannot sample. Route these to a pipeline with the")
        out.append("#   probabilistic_sampler processor, or use the Vector target, which can.")
    return "\n".join(out) + "\n"


def render_vector(plan: dict, field: str = ".message", inputs: str = "my_source") -> str:
    act = _active(plan)
    out = [
        "# Generated by logspend: Vector remap transform. Point `inputs` at your source,",
        "# then point your sink's `inputs` at \"logspend\". Run `logspend simulate` first.",
        "[transforms.logspend]",
        'type = "remap"',
        f'inputs = ["{inputs}"]',
        "drop_on_abort = true",
        "reroute_dropped = false",
        "source = '''",
        f"logspend_m = to_string({field}) ?? \"\"",
    ]
    for p in act:
        out.append(f"# {_comment(p)}")
        rx = p["regex"]
        if p["action"] == "drop":
            out.append(f"if match(logspend_m, r'{rx}') {{ abort }}")
        else:
            keep = int(p.get("sample_keep") or 10)
            out.append(f"if match(logspend_m, r'{rx}') && random_int(0, {keep}) != 0 {{ abort }}")
    out.append("'''")
    return "\n".join(out) + "\n"


def render_fluentbit(plan: dict, field: str = "log") -> str:
    act = _active(plan)
    out = [
        "# Generated by logspend: Fluent Bit grep filter (classic config).",
        "# Multiple Exclude rules are OR'ed: a record matching any of them is dropped.",
    ]
    drops = [p for p in act if p["action"] == "drop"]
    if drops:
        out += ["[FILTER]", "    Name    grep", "    Match   *"]
        for p in drops:
            out.append(f"    # {_comment(p)}")
            out.append(f"    Exclude {field} {p['regex']}")
    else:
        out.append("# (no drop rules in this plan)")
    for p in act:
        if p["action"] == "sample":
            out.append(f"# NOT APPLIED {_comment(p)}")
            out.append("#   The grep filter cannot sample; drop it, or use the Vector target.")
    return "\n".join(out) + "\n"


def render(plan: dict, target: str, field: str = None, inputs: str = "my_source") -> str:
    field = field or DEFAULT_FIELD[target]
    if target == "otel":
        return render_otel(plan, field)
    if target == "vector":
        return render_vector(plan, field, inputs)
    if target == "fluentbit":
        return render_fluentbit(plan, field)
    raise ValueError(f"unknown target {target!r} (choose from {', '.join(TARGETS)})")
